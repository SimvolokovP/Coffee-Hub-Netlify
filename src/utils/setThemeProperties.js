export function setLightProperties() {
	document.documentElement.style.setProperty('--accent-color', '#FDCB50')
	document.documentElement.style.setProperty('--bg-color', '#fff')
}

export function setDarkProperties() {
	document.documentElement.style.setProperty('--accent-color', '#FD8F01')
	document.documentElement.style.setProperty('--bg-color', '#1A1A1A')
}

